"""Generate JavaScript identifier range boundaries from Unicode 15.1.0."""
import hashlib
from urllib.request import urlopen


def main():
    with urlopen("https://www.unicode.org/Public/15.1.0/ucd/DerivedCoreProperties.txt") as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != "f55d0db69123431a7317868725b1fcbf1eab6b265d756d1bd7f0f6d9f9ee108b":
        raise ValueError("Unicode source checksum changed")
    tables = {"ID_Start": [], "ID_Continue": []}
    for line in data.decode().splitlines():
        fields = line.partition("#")[0].strip().split(";")
        if len(fields) != 2 or fields[1].strip() not in tables:
            continue
        endpoints = fields[0].strip().split("..")
        start, stop = int(endpoints[0], 16), int(endpoints[-1], 16) + 1
        bounds = tables[fields[1].strip()]
        if bounds and bounds[-1] == start:
            bounds[-1] = stop
        else:
            bounds.extend((start, stop))
    print('"""Unicode 15.1.0. Generated by tools/conformance/unicode_identifiers.py."""')
    print("# Unicode data license: see UNICODE-LICENSE.txt in this directory.")
    for name, bounds in tables.items():
        print(f"\n{name.upper()} = (")
        for i in range(0, len(bounds), 12):
            print("    " + ", ".join(hex(n) for n in bounds[i:i+12]) + ",")
        print(")")


if __name__ == "__main__":
    main()
