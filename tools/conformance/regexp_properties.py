"""Print the Unicode property and value aliases accepted by ECMAScript 2024."""
import hashlib
import json
import re
import textwrap
from urllib.request import urlopen

from bs4 import BeautifulSoup


def fetch(url, expected):
    with urlopen(url) as response:
        page = response.read()
    if hashlib.sha256(page).hexdigest() != expected:
        raise ValueError("Source digest changed: " + url)
    return page


def main():
    spec = fetch("https://tc39.es/ecma262/2024/multipage/text-processing.html",
                 "ffe3c94b1f7552723faa6258ef4b064e8cc1156ce756a6d9488b99ea9c21dd2c")
    aliases = fetch("https://www.unicode.org/Public/15.1.0/ucd/PropertyValueAliases.txt",
                    "4b7411fc592c4985e5f03643aa0bddfdfd45250ff1790d358926614d20e37652")
    document = BeautifulSoup(spec, "html.parser")
    groups = {}
    for group, table in (("BINARY", "binary-unicode-properties"), ("STRINGS", "binary-unicode-properties-of-strings")):
        groups[group] = {cell.get_text(strip=True) for cell in
                         document.select(f"#table-{table} tr > td:first-child")}
    groups["GENERAL_CATEGORY"], groups["SCRIPT"] = set(), set()
    for line in aliases.decode().splitlines():
        fields = [s.strip() for s in line.partition("#")[0].split(";")]
        if fields[0] in ("gc", "sc"):
            groups["GENERAL_CATEGORY" if fields[0] == "gc" else "SCRIPT"].update(fields[1:])
    scanner = fetch("https://raw.githubusercontent.com/microsoft/TypeScript/v5.9.3/src/compiler/scanner.ts",
                    "02f9e8f02e234b0e917e753a7b74f975c9b9b95f7f01ee4bc151081ed43dea49").decode()
    render(groups, scanner)


def render(groups, scanner):
    # The editions agree on membership. Preserve the TS iteration order for
    # deterministic spelling suggestions when two aliases have the same score.
    prefixes = {"BINARY": "const binaryUnicodeProperties =", "STRINGS": "const binaryUnicodePropertiesOfStrings =",
                "GENERAL_CATEGORY": "    General_Category: new Set", "SCRIPT": "    Script: new Set"}
    print('"""ECMAScript 2024 and Unicode 15.1.0. Generated by tools/conformance/regexp_properties.py."""')
    print("# Unicode data license: see UNICODE-LICENSE.txt in this directory.")
    for key, values in groups.items():
        line, = (s for s in scanner.splitlines() if s.startswith(prefixes[key]))
        ordered = json.loads(re.search(r"new Set\((\[.*?\])\)", line)[1])
        if set(ordered) != values:
            raise ValueError(f"Unicode property aliases differ for {key}")
        print(f'\n{key} = dict.fromkeys("""')
        print(textwrap.fill(" ".join(ordered), 96, break_long_words=False, break_on_hyphens=False))
        print('""".split()).keys()')


if __name__ == "__main__":
    main()
