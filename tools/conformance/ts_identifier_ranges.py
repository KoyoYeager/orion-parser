"""Generate the ES5 identifier ranges or check both target modes against TypeScript 5.9.3."""
import argparse
from io import StringIO
from pathlib import Path
from textwrap import wrap

from check_js_examples import acorn_asts
from check_typescript import COMPILER_SHA, TypeScriptPipeline, check_pin, run_compiler
from orionparser.languages.javascript.identifiers import identifier_char


ORACLE = """
const ts = require(process.argv[1]);
function bounds(target, predicate) {
    const result = [];
    let last = false;
    for (let ch = 0; ch <= 0x10ffff; ++ch) {
        const valid = predicate(ch, target);
        if (valid !== last) result.push(ch);
        last = valid;
    }
    return result;
}
process.stdout.write(JSON.stringify([ts.ScriptTarget.ES5, ts.ScriptTarget.ESNext].map(
    target => [ts.isIdentifierStart, ts.isIdentifierPart].map(fn => bounds(target, fn)))));
"""


def declarations(tables):
    out = StringIO()
    print('"""TypeScript 5.9.3 ES5 identifier boundaries generated by tools/conformance/ts_identifier_ranges.py."""', file=out)
    for name, bounds in zip(("START", "PART"), tables, strict=True):
        print(f"\n{name} = (", file=out)
        for line in wrap(", ".join(map(str, bounds)) + ",", width=104):
            print("    " + line, file=out)
        print(")", file=out)
    return out.getvalue()


def compare_escape_spelling(compiler, acorn):
    # scanner.ts drops the buffered plain characters preceding a second
    # braced escape. Pin the discrepancy separately from range membership.
    sources = [r"\u{61}b\u{63};", r"a\u0062c\u{64};", r"a\u{62}c\u0064;"]
    oracle = """
    const ts = require(process.argv[1]);
    const sources = JSON.parse(require("fs").readFileSync(0, "utf8"));
    process.stdout.write(JSON.stringify(sources.map(source => {
        const f = ts.createSourceFile("name.ts", source, ts.ScriptTarget.ESNext, true);
        if (f.parseDiagnostics.length) throw new Error("Unexpected syntax error");
        return f.statements[0].expression.text;
    })));
    """
    ts_names = run_compiler(compiler, oracle, sources)
    js = acorn_asts(acorn, [{"src": source, "goal": "script"} for source in sources])
    pipeline = TypeScriptPipeline("name.ts")
    names = [pipeline.parse(source)["body"][0]["expression"]["name"] for source in sources]
    if names != [ast["body"][0]["expression"]["name"] for ast in js] or names != ["abc", "abcd", "abcd"]:
        raise ValueError(f"Identifier StringValue mismatch: {names}")
    if ts_names != ["ac", "abd", "abcd"]:
        raise ValueError(f"The pinned TypeScript spelling discrepancy changed: {ts_names}")
    print("Three escape spellings match ECMAScript; two differ from the pinned TypeScript AST")


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("compiler", type=Path)
    cli.add_argument("--acorn", type=Path, help="Pinned Acorn 8.14.1 archive for the spelling comparison")
    cli.add_argument("--generate", action="store_true", help="Write Python declarations to stdout")
    args = cli.parse_args()
    check_pin(args.compiler, COMPILER_SHA)
    es5, latest = run_compiler(args.compiler, ORACLE, [])
    if args.generate:
        print(declarations(es5), end="")
        return 0
    if args.acorn is None:
        cli.error("--acorn is required when verifying identifier spellings")
    from orionparser.languages.typescript.pipeline import es5_identifier_char

    for name, tables, check in (("ES5", es5, es5_identifier_char), ("ESNext", latest, identifier_char)):
        for first, bounds in zip((True, False), tables, strict=True):
            changes = set(bounds)
            expected = False
            for code in range(0x110000):
                if code in changes:
                    expected = not expected
                if check(chr(code), first) != expected:
                    raise ValueError(f"{name} first={first} differs at U+{code:04X}")
    compare_escape_spelling(args.compiler, args.acorn)
    print("ES5 and ESNext identifier starts and continuations agree at all 1,114,112 code points")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
