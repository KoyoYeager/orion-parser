    "RSHIFT",
    # Comparison
    "LESS",
    "GREATER",
    "LESSEQUAL",
    "GREATEREQUAL",
    "EQEQUAL",
    "NOTEQUAL",
    # Assignment operators
    "EQUAL",
    "PLUSEQUAL",
